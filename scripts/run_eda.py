def section_segments(dataset) -> None:
    print("\n[5] SEGMENTS (training readings, recomputed. Metadata lifetime stats NOT used)")
    meta = dataset.metadata
    if meta is None:
        print("   metadata absent: skipped")
        return
    tr = TR_READINGS[TR_READINGS["timestamp"] <= TRAIN_END]
    tr = tr.loc[valid_reading_mask(tr)].merge(meta, on="vm_id", how="left", suffixes=("", "_meta"))
    rows = []
    for dim in ("vm_category", "virtual_core_bucket", "memory_gb_bucket"):
        vm_level = tr.groupby(["vm_id", dim])["avg_cpu"].mean().reset_index()
        for value, group in vm_level.groupby(dim):
            rows.append({
                "dimension": dim,
                "segment": str(value),
                "n_vms": int(group["vm_id"].nunique()),
                "vm_mean_cpu_mean": group["avg_cpu"].mean(),
                "vm_mean_cpu_median": group["avg_cpu"].median(),
                "vm_mean_cpu_p90": group["avg_cpu"].quantile(0.90),
            })
    seg = pd.DataFrame(rows)
    ver = tr.groupby("vm_id")["virtual_core_bucket"].first()
    saving = []
    base = seg.loc[seg["dimension"] == "virtual_core_bucket", "vm_mean_cpu_mean"].mean()
    for dimension in ("vm_category", "virtual_core_bucket", "memory_gb_bucket"):
        sub = seg[seg["dimension"] == dimension]
        w = sub["n_vms"] / sub["n_vms"].sum()
        saving += [{"dimension": dimension, "overall_vm_mean_cpu": float((w * sub["vm_mean_cpu_mean"]).sum())}]
    seg["share_of_vms_pct"] = seg.apply(
        lambda r: 100 * r["n_vms"] / seg.loc[seg["dimension"] == r["dimension"], "n_vms"].sum(), axis=1
    )
    save(seg, "segment_profiles_train.csv")
    print(seg.to_string(index=False))

    # Deployment size (number of VMs sharing a deployment).
    dep = (meta.groupby("deployment_id")["vm_id"].nunique()
           .rename("deployment_vm_count").reset_index())
    dep["size_bucket"] = pd.cut(dep["deployment_vm_count"], bins=[0, 1, 2, 4, 8, 1e9],
                                labels=["1", "2", "3-4", "5-8", "9+"])
    dep_vm = (meta[["vm_id", "deployment_id"]]
              .merge(dep[["deployment_id", "deployment_vm_count", "size_bucket"]], on="deployment_id", how="left")
              .merge(tr.groupby("vm_id")["avg_cpu"].mean().rename("vm_mean_cpu").reset_index(),
                     on="vm_id", how="inner"))
    dep_size = dep_vm.groupby("size_bucket", observed=True).agg(
        n_vms=("vm_id", "nunique"), n_deployments=("deployment_id", "nunique"),
        vm_mean_cpu_mean=("vm_mean_cpu", "mean"), vm_mean_cpu_median=("vm_mean_cpu", "median"),
    ).reset_index()
    save(dep_size, "deployment_size_segments.csv")
    print(dep_size.to_string(index=False))

    plt.figure(figsize=(7, 3))
    cats = [str(c) for c in seg.loc[seg["dimension"] == "vm_category", "segment"]]
    plt.bar(cats, seg.loc[seg["dimension"] == "vm_category", "vm_mean_cpu_mean"], color="#548235")
    plt.ylabel("mean of per-VM mean CPU (%)"); plt.title("Utilisation by VM category (training window)")
    fig("fig03_segments_category.png")


def section_peaks(series, split, step) -> None:
    print("\n[6] PEAKS (threshold fixed from the training window only)")
    tr = split.train
    y = tr["aggregate_cpu_utilization"].to_numpy(dtype=float)
    thr90 = float(np.quantile(y, 0.90))
    thr75 = float(np.quantile(y, 0.75))
    peak = pd.DataFrame([{
        "peak_threshold_pp_top_decile": thr90,
        "upper_quartile_threshold_pp": thr75,
        "n_peak_timestamps_train": int((y >= thr90).sum()),
        "pct_time_at_peak": 100 * float((y >= thr90).mean()),
        "pct_time_low_demand_bottom_decile": 10.0,
        "peak_hours_of_day_distinct": int(len(np.unique((tr.loc[tr['aggregate_cpu_utilization'] >= thr90, 'timestamp'] // 3600)))),
        "note": "11 hours of data: 'peak periods' are descriptive within the window, not a daily cycle",
    }])
    save(peak, "peak_definitions_train.csv")
    print(peak.T.to_string(header=False))
    pd.Series({"peak_threshold_pp_top_decile": thr90}).to_csv(ART / "peak_threshold.json")
    (ART / "peak_threshold.json").write_text(json.dumps({"peak_threshold_pp_top_decile": thr90}, indent=2))

    # Autocorrelation decay summary: how far ahead is signal left?
    ac = acf_full(y, min(48, len(y) - 2))
    below = np.where(np.abs(ac[1:]) < 1.96 / np.sqrt(len(y)))[0]
    first_below = int(below[0] + 1) if len(below) else None
    decay = pd.DataFrame([{
        "first_lag_inside_95pct_band": first_below,
        "minutes_to_decay": None if first_below is None else first_below * step / 60.0,
    }])
    save(decay, "acf_decay.csv")
    print(decay.T.to_string(header=False))


