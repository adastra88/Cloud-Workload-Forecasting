def section_structure(dataset, series, split, step) -> dict:
    print("\n[1] STRUCTURAL INTEGRITY (full file, no target values emitted)")
    rep = dataset.report
    print("  ", {k: rep[k] for k in ("n_rows", "n_vms", "n_timestamps", "duplicate_vm_timestamp", "invalid_reading_rows")})
    meta = dataset.metadata
    grid = pd.DataFrame([
        {"check": "rows", "value": rep["n_rows"]},
        {"check": "distinct_vms", "value": rep["n_vms"]},
        {"check": "distinct_timestamps", "value": rep["n_timestamps"]},
        {"check": "modal_step_seconds", "value": rep["modal_step"]},
        {"check": "non_modal_steps", "value": rep["n_gaps_vs_modal"]},
        {"check": "duplicate_vm_timestamp", "value": rep["duplicate_vm_timestamp"]},
        {"check": "null_cells", "value": sum(rep["null_counts"].values())},
        {"check": "invalid_avg_cpu_rows", "value": rep["invalid_reading_rows"]},
        {"check": "min_cpu_gt_max_cpu_rows", "value": rep["min_gt_max_rows"]},
        {"check": "min_readings_per_vm", "value": rep["readings_per_vm_min"]},
        {"check": "max_readings_per_vm", "value": rep["readings_per_vm_max"]},
    ])
    save(grid, "structure_checks.csv")

    sharing = []
    for ts, group in dataset.readings.groupby("timestamp", sort=False):
        n_valid = int(valid_reading_mask(group).sum())
        sharing.append({"n_valid_at_timestamp": n_valid})
    share = pd.DataFrame(sharing)["n_valid_at_timestamp"].value_counts().sort_index()
    shape = pd.DataFrame({"n_valid_at_timestamp": share.index, "n_timestamps": share.values})
    save(shape, "coverage_per_timestamp.csv")
    print(f"   timestamps with a shared VM set: {len(shape)} distinct (n_valid) values -> "
          f"{'complete shared grid' if len(shape) == 1 else 'uneven coverage'}")

    if meta is not None:
        train_end = split.train_end_timestamp
        meta = meta.copy()
        meta["created_before_train_end"] = meta["timestamp_vm_created"] <= train_end
        # Churn is CENSORED at the training-window end: deletions after that are
        # not observable as evidence during training.
        meta["deleted_within_training"] = meta["timestamp_vm_deleted"] <= train_end
        churn = pd.DataFrame({
            "group": meta["vm_category"].astype(str),
            "n_vms": 1,
            "created_by_train_end": meta["created_before_train_end"].astype(int),
            "deleted_by_train_end": meta["deleted_within_training"].astype(int),
        }).groupby("group").sum().reset_index()
        churn["pct_created_by_train_end"] = 100 * churn["created_by_train_end"] / churn["n_vms"]
        churn["pct_deleted_by_train_end"] = 100 * churn["deleted_by_train_end"] / churn["n_vms"]
        save(churn, "churn_by_category.csv")

        lifetime = ((meta["timestamp_vm_deleted"] - meta["timestamp_vm_created"]) / 86400.0)
        life = pd.DataFrame({
            "stat": ["n_vms", "median_lifetime_days", "p10_lifetime_days", "p90_lifetime_days",
                     "pct_created_by_train_end", "pct_deleted_within_trace_window"],
            "value": [
                len(meta), lifetime.median(), lifetime.quantile(0.10), lifetime.quantile(0.90),
                100 * meta["created_before_train_end"].mean(),
                100 * (meta["timestamp_vm_deleted"] <= series["timestamp"].max()).mean(),
            ],
        })
        save(life, "lifetime_summary.csv")

    return {"n_valid_values_per_timestamp": len(shape)}


def section_targets_training(series, split, step) -> None:
    print("\n[2] TARGETS OVER THE TRAINING WINDOW ONLY")
    tr = split.train
    rows = []
    for col in ("active_vm_count", "aggregate_cpu_utilization"):
        x = tr[col].to_numpy(dtype=float)
        d = np.diff(x)
        rows.append({
            "target": col,
            "n": len(x),
            "mean": x.mean(),
            "std": x.std(ddof=1),
            "min": x.min(),
            "p05": np.percentile(x, 5),
            "p50": np.percentile(x, 50),
            "p95": np.percentile(x, 95),
            "max": x.max(),
            "cv_pct": 100 * x.std(ddof=1) / x.mean() if x.mean() else np.nan,
            "is_constant": bool(np.allclose(x, x[0])),
            "mean_abs_one_step_change": np.abs(d).mean() if len(d) else np.nan,
            "naive_mae_in_sample": np.abs(d).mean() if len(d) else np.nan,
            "naive_rmse_in_sample": float(np.sqrt(np.mean(d**2))) if len(d) else np.nan,
            "mean_one_step_change": d.mean() if len(d) else np.nan,
        })
    summary = pd.DataFrame(rows)
    save(summary, "target_summary_train.csv")
    print(summary[["target", "mean", "std", "min", "max", "is_constant"]].to_string(index=False))


def section_temporal(series, split, step) -> None:
    print("\n[3] TEMPORAL PATTERNS (training window only)")
    tr = split.train
    y = tr["aggregate_cpu_utilization"].to_numpy(dtype=float)
    n = len(y)
    lags = [1, 2, 3, 6, 12, 24, 36, 48, 72]
    ac = autocorr(y, lags)
    acdf = pd.DataFrame({"lag": list(ac), "acf": list(ac.values())})
    acdf["lag_minutes"] = acdf["lag"] * step / 60.0
    save(acdf, "acf_train.csv")

    max_lag = min(48, n - 2)
    curve = acf_full(y, max_lag)
    ci = 1.96 / np.sqrt(n)
    pacf_vals = []
    # PACF via Durbin-Levinson (avoids extra statsmodels call for a curve).
    phi = np.zeros((max_lag + 1, max_lag + 1))
    for k in range(1, max_lag + 1):
        num = curve[k] - sum(phi[k - 1, j] * curve[k - j] for j in range(1, k))
        den = 1.0 - sum(phi[k - 1, j] * curve[j] for j in range(1, k))
        phi[k, k] = num / den if den != 0 else 0.0
        for j in range(1, k):
            phi[k, j] = phi[k - 1, j] - phi[k, k] * phi[k - 1, k - j]
        pacf_vals.append(phi[k, k])
    corr = pd.DataFrame({
        "lag": np.arange(max_lag + 1),
        "acf": curve,
        "pacf": [1.0] + pacf_vals,
    })
    corr["ci_95"] = ci
    save(corr, "acf_pacf_train.csv")

    # trend: OLS slope with Newey-West (lag 6) standard error
    t = np.arange(n, dtype=float)
    X = np.column_stack([np.ones(n), t])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    slope_per_hour = beta[1] * 3600.0 / step
    lags_nw = 6
    S = (X * resid[:, None]).T @ (X * resid[:, None])
    for k in range(1, lags_nw + 1):
        w = 1.0 - k / (lags_nw + 1)
        G = (X[k:] * resid[k:, None]).T @ (X[:-k] * resid[:-k, None])
        S += w * (G + G.T)
    cov = np.linalg.pinv(X.T @ X) @ S @ np.linalg.pinv(X.T @ X)
    slope_se_per_hour = float(np.sqrt(max(cov[1, 1], 0.0))) * 3600.0 / step
    stat = pd.DataFrame([{
        "trend_slope_pp_per_hour": float(slope_per_hour),
        "trend_slope_se_pp_per_hour": slope_se_per_hour,
        "trend_t_stat": float(slope_per_hour / slope_se_per_hour) if slope_se_per_hour else np.nan,
        "adf_pvalue": adf_pvalue(y),
        "kpss_pvalue": kpss_pvalue(y),
        "adf_pvalue_diff": adf_pvalue(np.diff(y)),
        "kpss_pvalue_diff": kpss_pvalue(np.diff(y)),
        "acf_lag1": ac[1],
        "acf_lag12": ac[12],
        "acf_lag24": ac[24],
        "ci_95_acf_band": ci,
        "n_training": n,
    }])
    save(stat, "stationarity_trend.csv")
    print(stat.T.to_string(header=False))

    # Composition vs genuine load change.  With a fixed VM set at every
    # timestamp (true for this release) a between-VM "composition" term cannot
    # move the aggregate; but a *fixed-effects* split still tells us how much of
    # total utilisation variance is explained by which VM a reading belongs to
    # versus when it was taken.  That is the number that tells an operator
    # whether the aggregate moves because workloads change or because the
    # population is heterogeneous.
    tr_readings = TR_READINGS[TR_READINGS["timestamp"] <= split.train_end_timestamp]
    tr_readings = tr_readings.loc[valid_reading_mask(tr_readings)]
    vm_ts = tr_readings.groupby(["vm_id", "timestamp"])["avg_cpu"].mean().unstack()
    vm_means = vm_ts.mean(axis=1)
    time_means = vm_ts.mean(axis=0)
    grand = float(np.nanmean(vm_ts.to_numpy()))
    vm_effect = (vm_means - grand).to_numpy()[:, None]
    time_effect = (time_means - grand).to_numpy()[None, :]
    resid_effect = vm_ts.to_numpy() - grand - vm_effect - time_effect
    var_vm = float(np.nanvar(np.broadcast_to(vm_effect, vm_ts.shape)))
    var_time = float(np.nanvar(np.broadcast_to(time_effect, vm_ts.shape)))
    var_resid = float(np.nanvar(resid_effect))
    total = var_vm + var_time + var_resid
    comp = pd.DataFrame([{
        "var_between_vm_levels": var_vm,
        "var_common_time_component": var_time,
        "var_idiosyncratic": var_resid,
        "share_between_vm_pct": 100 * var_vm / total if total else np.nan,
        "share_common_time_pct": 100 * var_time / total if total else np.nan,
        "share_idiosyncratic_pct": 100 * var_resid / total if total else np.nan,
        "n_vms": int(vm_ts.shape[0]),
        "n_timestamps": int(vm_ts.shape[1]),
    }])
    save(comp, "composition_vs_load.csv")
    print(comp.T.to_string(header=False))
    within = vm_ts.sub(vm_means, axis=0)

    # Aggregate movement decomposition (first differences).
    agg_mean = vm_ts.mean(axis=0)
    d_agg = np.asarray(agg_mean, dtype=float)
    d_agg = np.diff(d_agg)
    d_within = np.diff(np.asarray(vm_ts.sub(vm_means, axis=0), dtype=float), axis=1).mean(axis=0)
    decomp = pd.DataFrame([{
        "std_aggregate_change_pp": float(d_agg.std(ddof=1)),
        "std_within_vm_change_component_pp": float(d_within.std(ddof=1)),
        "corr_aggregate_with_within_component": float(np.corrcoef(d_agg, d_within)[0, 1]),
        "mean_abs_aggregate_change_pp": float(np.abs(d_agg).mean()),
        "mean_abs_within_component_change_pp": float(np.abs(d_within).mean()),
        "note": "the between-VM term sums to zero inside each timestamp when every VM is present, so aggregate movement in this release is 100% within-VM load change; composition effects can only enter through membership changes",
    }])
    save(decomp, "movement_decomposition.csv")
    print(decomp.T.to_string(header=False))

    # Mean hides hot VMs.
    per_ts = tr_readings.groupby("timestamp")["avg_cpu"]
    hide = pd.DataFrame({
        "cross_vm_p95": per_ts.quantile(0.95),
        "cross_vm_p99": per_ts.quantile(0.99),
        "cross_vm_max": per_ts.max(),
        "aggregate_mean": per_ts.mean(),
        "share_above_80": tr_readings.assign(hi=tr_readings["avg_cpu"] >= 80).groupby("timestamp")["hi"].mean(),
    })
    hide_summary = pd.DataFrame([{
        "mean_of_aggregate_mean": hide["aggregate_mean"].mean(),
        "mean_of_cross_vm_p95": hide["cross_vm_p95"].mean(),
        "mean_of_cross_vm_p99": hide["cross_vm_p99"].mean(),
        "mean_of_cross_vm_max": hide["cross_vm_max"].mean(),
        "ratio_p95_to_mean": hide["cross_vm_p95"].mean() / hide["aggregate_mean"].mean(),
        "mean_share_vms_above_80pct": 100 * hide["share_above_80"].mean(),
        "mean_share_vms_above_90pct": 100 * tr_readings.assign(hi=tr_readings["avg_cpu"] >= 90).groupby("timestamp")["hi"].mean().mean(),
    }])
    save(hide_summary, "mean_hides_tails.csv")
    print(hide_summary.T.to_string(header=False))

    # Figures
    fig_series(series, split)


